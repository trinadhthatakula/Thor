package com.valhalla.thor.data.kernel

import com.valhalla.superuser.Shell
import java.io.File
import java.util.UUID

/** A fresh shell, without mount-master or a shared interactive shell's environment. */
internal class KernelFlashRunner : AutoCloseable {
    private val shell = Shell.Builder.create().setFlags(0).setTimeout(10).build()
    private var busybox: String? = null

    fun slotInfo(): KernelSlotInfo {
        check(shell.isRoot) { "Root access is required to inspect the target slot." }
        val lines = mutableListOf<String?>()
        val result = shell.newJob().add(
            "/system/bin/getprop ro.boot.slot_suffix",
            "/system/bin/getprop ro.boot.slot",
            "/system/bin/getprop ro.build.ab_update",
        ).to(lines, null).exec()
        if (result.code != 0 || lines.size != 3) return KernelSlotInfo()
        return kernelSlotInfo(lines[0].orEmpty(), lines[1].orEmpty(), lines[2].orEmpty())
    }

    fun bootId(): String? {
        check(shell.isRoot) { "Root access is required to read the kernel boot identity." }
        val lines = mutableListOf<String?>()
        val result = shell.newJob().add("/system/bin/cat /proc/sys/kernel/random/boot_id").to(lines, null).exec()
        if (result.code != 0) return null
        val value = lines.singleOrNull()?.trim() ?: return null
        return runCatching { value.takeIf { UUID.fromString(it).toString() == it } }.getOrNull()
    }

    fun prepare(directory: File) {
        check(shell.isRoot) { "Thor must be granted root to flash a kernel." }
        busybox = BUSYBOX_PATHS.firstOrNull { candidate ->
            val command = "[ -x ${quote(candidate)} ] && ${quote(candidate)} ash -c " +
                quote("[ \"\$(${quote(candidate)} id -u)\" = 0 ]") +
                " && ${quote(candidate)} unzip --help >/dev/null 2>&1" +
                " && ${quote(candidate)} mkfifo --help >/dev/null 2>&1" +
                " && printf x | ${quote(candidate)} ash -c " +
                quote("IFS= read -r -n 1 value && [ \"\$value\" = x ]")
            shell.newJob().add(command).exec().code == 0
        }
        val executable = checkNotNull(busybox) {
            "A working Magisk, KernelSU or APatch BusyBox is required. Update your root manager."
        }
        val bootstrap = File(directory, "bootstrap")
        check(bootstrap.mkdir()) { "Cannot create the installer environment." }
        check(shell.newJob().add("${quote(executable)} --install -s ${quote(bootstrap.path)}").exec().code == 0) {
            "Cannot prepare BusyBox applets."
        }
    }

    /** Blocking by design: the foreground owner retains this job through complete output drain. */
    fun flash(directory: File, archive: File, slot: KernelSlotSelection, onLine: (String) -> Unit): Int {
        val executable = checkNotNull(busybox)
        check(shell.isRoot && shell.isAlive) { "The root shell is no longer available." }
        val output = object : AbstractMutableList<String?>() {
            override val size: Int get() = 0
            override fun get(index: Int): String? = throw IndexOutOfBoundsException()
            override fun set(index: Int, element: String?): String? = throw IndexOutOfBoundsException()
            override fun removeAt(index: Int): String? = throw IndexOutOfBoundsException()
            override fun add(index: Int, element: String?) { element?.let(onLine) }
        }
        return shell.newJob().add(command(directory, executable, slot, archive)).to(output, output).exec().code
    }

    fun clean(directory: File) {
        // The path is generated by Thor; no archive or display filename becomes a shell argument.
        if (shell.isAlive) check(shell.newJob().add("/system/bin/rm -rf ${quote(directory.path)}").exec().code == 0) {
            "Cannot remove the installer working directory."
        }
    }

    override fun close() { shell.close() }

    companion object {
        private val BUSYBOX_PATHS = listOf(
            "/data/adb/ksu/bin/busybox", "/data/adb/magisk/busybox", "/data/adb/ap/bin/busybox",
        )

        internal fun quote(value: String): String {
            require('\u0000' !in value)
            return "'" + value.replace("'", "'\\''") + "'"
        }

        // ash read bounds memory even without newlines. Its builtin printf flushes each chunk;
        // BusyBox fold buffers small logs until exit when stdout is a pipe.
        internal const val OUTPUT_READER = "while line=; IFS= read -r -n 1024 line || [ -n \"\$line\" ]; do printf '%s\\n' \"\$line\" || exit 125; done"

        internal fun command(
            directory: File, busybox: String,
            slot: KernelSlotSelection = KernelSlotSelection.PACKAGE_DEFAULT,
            archive: File = File(directory, "package.zip"),
        ): String {
            require(slot != KernelSlotSelection.BOTH) { "Both slots must run as two separate passes." }
            return """
            (
              cd ${quote(directory.path)} || exit 1
              unset ASH_STANDALONE ENV BASH_ENV
              export PATH=${quote(File(directory, "bootstrap").path + ":/system/bin:/system/xbin")}
              [ "${'$'}(${quote(busybox)} id -u)" = 0 ] || exit 1
              export AKHOME=${quote(File(directory, "unpacked").path)}
              ${slot.installerValue?.let { "export SLOT_SELECT=${quote(it)}" } ?: "unset SLOT_SELECT"}
              ${quote(busybox)} mkfifo ${quote(File(directory, "output.pipe").path)} || exit 1
              ${quote(busybox)} ash -c ${quote(OUTPUT_READER)} < ${quote(File(directory, "output.pipe").path)} &
              reader=${'$'}!
              ${quote(busybox)} ash ${quote(File(directory, "update-binary").path)} 3 1 ${quote(archive.path)} > ${quote(File(directory, "output.pipe").path)} 2>&1
              result=${'$'}?
              wait "${'$'}reader"
              drained=${'$'}?
              ${quote(busybox)} rm -f ${quote(File(directory, "output.pipe").path)}
              [ "${'$'}drained" = 0 ] || exit 125
              exit "${'$'}result"
            )
        """.trimIndent()
        }
    }
}
